// 멀티 플레이 기본 이름: 형용사 + 명사 (AI 나라 이름 '색 + 동물'과 겹치지 않게 색·동물 낱말은 쓰지 않는다).
// 이름 칸 10글자 안에 들어가게 (형용사 ≤ 4글자 + 빈칸 + 명사 ≤ 5글자).

const ADJ = ['용감한', '고요한', '날쌘', '지혜로운', '떠도는', '굳센', '조용한', '재빠른', '느긋한', '외로운',
  '배고픈', '졸린', '수줍은', '단단한', '빛나는', '겁없는', '엉뚱한', '부지런한', '차가운', '따뜻한'];
const NOUN = ['나그네', '숲지기', '뱃사공', '대장장이', '사냥꾼', '양치기', '파수꾼', '농부', '나무꾼', '어부',
  '방랑자', '산지기', '등대지기', '탐험가', '궁수', '기사', '목동', '석공', '약초꾼', '별지기'];

const pick = <T>(a: readonly T[]) => a[Math.floor(Math.random() * a.length)];

/** 무작위 이름 하나 (예: '느긋한 등대지기'). */
export function randomName(): string { return `${pick(ADJ)} ${pick(NOUN)}`; }
