type Rect = [number, number, number, number];

/** 점 사각형들을 한 색으로. */
function px(fill: string, rects: Rect[]): string {
  return `<path fill="${fill}" d="${rects.map(([x, y, w, h]) => `M${x} ${y}h${w}v${h}h${-w}z`).join('')}"/>`;
}

function svg(body: string, size: number): string {
  return `<svg class="ico" width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${body}</svg>`;
}

/** 엇갈린 칼: 왼쪽 위 → 오른쪽 아래 칼과 그 거울. */
function swords(): string {
  const light: Rect[] = [], dark: Rect[] = [], guard: Rect[] = [], grip: Rect[] = [];
  for (const m of [false, true]) {
    const X = (x: number, w = 1) => (m ? 16 - x - w : x);
    for (let i = 1; i <= 8; i++) { light.push([X(i, 2), i, 2, 1]); dark.push([X(i), i + 1, 1, 1]); }
    for (const [x, y] of [[12, 8], [11, 9], [9, 11], [8, 12]]) guard.push([X(x), y, 1, 1]);
    grip.push([X(11, 2), 11, 2, 2], [X(13, 2), 13, 2, 2]);
  }
  return px('rgb(140,146,162)', dark) + px('rgb(226,230,240)', light) + px('rgb(214,170,70)', guard) + px('rgb(120,78,44)', grip);
}

